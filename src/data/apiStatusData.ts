// Helper to generate 90-day history with 99.98% - 100% realistic uptime distributions
export function generate90DayUptimeHistory(baseUptime: number = 99.99, degradedDaysCount: number = 0): DayUptimeRecord[] {
  const records: DayUptimeRecord[] = [];
  const today = new Date();

  // Deterministic degraded days placement
  const degradedIndices = new Set<number>();
  if (degradedDaysCount > 0) {
    degradedIndices.add(24);
    if (degradedDaysCount > 1) degradedIndices.add(67);
  }

  for (let i = 89; i >= 0; i--) {
    const d = new Date(today);
    d.setDate(today.getDate() - i);
    const dateStr = d.toISOString().split('T')[0];

    if (degradedIndices.has(i)) {
      records.push({
        date: dateStr,
        uptime: 99.4,
        status: 'degraded',
        incidentCount: 1,
      });
    } else {
      records.push({
        date: dateStr,
        uptime: 100.0,
        status: 'operational',
        incidentCount: 0,
      });
    }
  }

  return records;
}

